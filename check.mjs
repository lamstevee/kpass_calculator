import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
const calculate = runInNewContext(`${readFileSync(new URL('./app.js', import.meta.url), 'utf8')}\ncalculate`, {});
const base = { amount: 80000, ordinary: 80000, rides: 42, firstMonth: false, card: true, region: 'local', type: 'general', month: 'normal' };
assert.equal(JSON.stringify(calculate(base)), JSON.stringify({ basic: 16000, general: 25000, plus: 0, refund: 25000, winner: '일반형 적용', cashback: 10000, net: 45000 }));
assert.equal(calculate({ ...base, rides: 14 }).refund, 0);
assert.equal(calculate({ ...base, amount: 160000, ordinary: 40000 }).winner, '플러스형 적용');
assert.equal(calculate({ ...base, amount: 80000, ordinary: 80000, month: 'temporary' }).general, 53000);
assert.equal(calculate({ ...base, month: 'temporary', offpeak: 20000 }).basic, 22000);
assert.equal(calculate({ ...base, region: 'metro', month: 'temporary' }).general, 50000);
assert.equal(calculate({ ...base, type: 'youth', month: 'temporary' }).general, 57000);
assert.equal(calculate({ ...base, amount: 250000, ordinary: 0, card: false, regionalException: true }).basic, 50000);
assert.equal(calculate({ ...base, month: 'normal', offpeak: 20000 }).basic, 22000);
assert.equal(calculate({ ...base, month: 'early', offpeak: 20000 }).basic, 16000);
assert.equal(calculate({ ...base, tmoney: false }).net, 70000);
assert.equal(calculate({ ...base, rides: 70 }).general, 25000);
assert.equal(calculate({ ...base, rides: 70 }).basic, null);
console.log('계산 확인 완료');
